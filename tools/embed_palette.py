"""Embed plugin/palette/index.html into the plug-in as a C++ string literal.

  python3 tools/embed_palette.py      (run after editing the palette; the build does not run it)

Output: plugin/src/palette/PaletteHtml.generated.inc (kPaletteHtml). The plug-in writes it to
Plug-ins/Data/vw-mcp/palette/index.html when the palette opens, so no resource extraction is needed.
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
html = (ROOT / 'plugin/palette/index.html').read_text()
delim = 'VWMCPHTML'
assert f'){delim}"' not in html
out = ROOT / 'plugin/src/palette/PaletteHtml.generated.inc'
out.write_text('// GENERATED by tools/embed_palette.py from plugin/palette/index.html - do not edit.\n'
               f'static const char* kPaletteHtml = R"{delim}({html}){delim}";\n')
print(f'{len(html) // 1024} KB -> {out.relative_to(ROOT)}')
